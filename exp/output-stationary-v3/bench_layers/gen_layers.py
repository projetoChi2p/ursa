#!/usr/bin/env python3
"""Generate the layer-shape GEMM bench for URSA (ursa_layers.h).

Every convolution and fully connected layer becomes one GEMM C = A x B with
    P = output channels, M = input channels x kernel area, Q = output pixels
(A = weights, B = im2col of the activations, batch 1). The board app splits
each GEMM into URSA calls exactly as the network runtime does (reduction in
chunks of at most MAX_M, calls sized to the memory windows) and times them.

Two groups of networks:
  * mendes: the satellite networks of the netmendes tests (PatternNet and
    RESISC45). Their shapes are read from the generated *_hwtest.cpp files
    (the urt_gemm_init calls), so they are the shapes the board runs.
    The attention matmuls of the ViTs are built at run time and are not in
    the table; their static linear layers are.
  * ref: the ImageNet networks the related work reports on Zynq-class boards
    (ResNet-18: SECDA, VTA; MobileNetV1: SECDA; VGG-16: FlexCNN and others).
    Depthwise convolutions are not a GEMM and are left out (marked in the
    table name list); every other layer is included.

Usage:
    python3 gen_layers.py --netmendes ../vitis_component/netmendes \
        --out ../vitis_component/mxm-ursa/src/ursa_layers.h --csv layers.csv
"""
import argparse
import csv
import glob
import os
import re


def conv(name, cin, cout, k, hout, wout=None):
    wout = hout if wout is None else wout
    return (name, cout, cin * k * k, hout * wout)


def fc(name, fin, fout):
    return (name, fout, fin, 1)


def resnet18_imagenet():
    L = [conv("conv1", 3, 64, 7, 112)]
    for b in range(2):
        L += [conv(f"layer1.{b}.conv1", 64, 64, 3, 56), conv(f"layer1.{b}.conv2", 64, 64, 3, 56)]
    for s, (cin, c, h) in enumerate([(64, 128, 28), (128, 256, 14), (256, 512, 7)], start=2):
        L += [conv(f"layer{s}.0.conv1", cin, c, 3, h), conv(f"layer{s}.0.conv2", c, c, 3, h),
              conv(f"layer{s}.0.downsample", cin, c, 1, h),
              conv(f"layer{s}.1.conv1", c, c, 3, h), conv(f"layer{s}.1.conv2", c, c, 3, h)]
    L += [fc("fc", 512, 1000)]
    return L


def vgg16_imagenet():
    cfg = [(3, 64, 224), (64, 64, 224), (64, 128, 112), (128, 128, 112),
           (128, 256, 56), (256, 256, 56), (256, 256, 56),
           (256, 512, 28), (512, 512, 28), (512, 512, 28),
           (512, 512, 14), (512, 512, 14), (512, 512, 14)]
    L = [conv(f"conv{i+1}", cin, cout, 3, h) for i, (cin, cout, h) in enumerate(cfg)]
    L += [fc("fc6", 512 * 7 * 7, 4096), fc("fc7", 4096, 4096), fc("fc8", 4096, 1000)]
    return L


def mobilenetv1_imagenet():
    # (cin, cout, output size) of the pointwise convolutions; the depthwise
    # 3x3 before each one is not a GEMM and is not in the bench.
    pw = [(32, 64, 112), (64, 128, 56), (128, 128, 56), (128, 256, 28), (256, 256, 28),
          (256, 512, 14)] + [(512, 512, 14)] * 5 + [(512, 1024, 7), (1024, 1024, 7)]
    L = [conv("conv1", 3, 32, 3, 112)]
    L += [conv(f"pw{i+1}", cin, cout, 1, h) for i, (cin, cout, h) in enumerate(pw)]
    L += [fc("fc", 1024, 1000)]
    return L


REF = [("resnet18_imagenet", resnet18_imagenet()),
       ("vgg16_imagenet", vgg16_imagenet()),
       ("mobilenetv1_pw_imagenet", mobilenetv1_imagenet())]

INIT_RE = re.compile(r'urt_gemm_init\(&\w+\[\d+\],\s*"(?P<name>[^"]+)",\s*(?P<p>\d+),\s*(?P<m>\d+),\s*(?P<q>\d+),')


def mendes_nets(root):
    nets = []
    for f in sorted(glob.glob(os.path.join(root, "satellite", "*_hwtest.cpp"))):
        stem = os.path.basename(f)[:-len("_hwtest.cpp")]
        layers = []
        with open(f) as fh:
            for line in fh:
                if "urt_gemm_init(&" not in line:
                    continue
                m = INIT_RE.search(line)
                if m:
                    layers.append((m.group("name"), int(m.group("p")), int(m.group("m")), int(m.group("q"))))
        if layers:
            nets.append((stem, layers))
    return nets


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--netmendes", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--csv", default=None)
    a = ap.parse_args()

    groups = [("mendes", n, l) for n, l in mendes_nets(a.netmendes)] + \
             [("ref", n, l) for n, l in REF]

    rows = []
    for grp, net, layers in groups:
        for name, p, m, q in layers:
            rows.append((grp, net, name, p, m, q))

    with open(a.out, "w") as f:
        f.write("/* Generated by bench_layers/gen_layers.py -- do not edit.\n"
                " * One row per GEMM layer: C (P x Q) = A (P x M) x B (M x Q), batch 1.\n"
                " * group: mendes = netmendes satellite networks (shapes from the\n"
                " * generated tests); ref = ImageNet networks of the related work. */\n")
        f.write("#ifndef URSA_LAYERS_H\n#define URSA_LAYERS_H\n#include <stdint.h>\n\n")
        f.write("typedef struct { const char *group, *net, *name; uint16_t P; uint32_t M; uint32_t Q; } ursa_layer_t;\n\n")
        f.write("static const ursa_layer_t ursa_layers[] = {\n")
        for grp, net, name, p, m, q in rows:
            f.write(f'    {{"{grp}", "{net}", "{name}", {p}, {m}, {q}}},\n')
        f.write("};\n#define URSA_NUM_LAYERS (sizeof(ursa_layers) / sizeof(ursa_layers[0]))\n\n#endif\n")

    if a.csv:
        with open(a.csv, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["group", "net", "layer", "P", "M", "Q", "macs"])
            for grp, net, name, p, m, q in rows:
                w.writerow([grp, net, name, p, m, q, p * m * q])

    nets = {}
    for grp, net, name, p, m, q in rows:
        nets.setdefault((grp, net), [0, 0])
        nets[(grp, net)][0] += 1
        nets[(grp, net)][1] += p * m * q
    for (grp, net), (n, macs) in nets.items():
        print(f"{grp:6s} {net:40s} {n:3d} layers {macs/1e6:10.1f} MMAC")
    print(f"total {len(rows)} layers, {sum(v[1] for v in nets.values())/1e9:.2f} GMAC")


if __name__ == "__main__":
    main()
