#!/usr/bin/env python3
"""Port the netmendes network tests to the URSA v3 memory layout.

Each *_hwtest.cpp embeds the same copy of the ursa_rt.h runtime (generated by
src/codegen in ViT-Research). This script rewrites, in that runtime only, the
parts that depend on the IP's memory layout, and leaves the network, weights,
images and golden logits untouched:

  urt_plan      A packed tile-major per reduction chunk (ursa_v3_layout.h)
  urt_tile      window limits with the v3 packed sizes of A and B
  urt_gemm_run  B packed in DDR and sent in one block copy; A streamed with
                the v3 block size; C copied out in one block and de-tiled
                (or added, for chunks after the first) on the ARM
  urt_model_mxm host model of the v3 IP (packed A and B, tile-major C)
  urt_report    MACs per inference printed in 64 bits (it was cast to a
                32-bit unsigned long on the ARM and wrapped above 4.29 GMAC:
                resnet18_patternnet_small reported 0.879 GMAC for 5.17)

The permanent fix belongs in the generator (src/codegen/backends/ursa/
runtime/ursa_rt.h); this is the same change applied to the generated files.

Usage:
    python3 patch_runtime.py <v2 netmendes dir> <out dir>
"""
import glob
import os
import sys


def rep(s, old, new, count=1):
    n = s.count(old)
    if n != count:
        raise SystemExit("patch anchor found %d times (expected %d):\n%s" % (n, count, old[:200]))
    return s.replace(old, new)


def patch(s):
    # 0. banner + layout helpers
    s = rep(s, """/* Bytes of the packed A operand of a P x M weight matrix (any chunking). */
#define URT_A_BYTES(P, M)   (URT_UP((P), SA_SIZE) * URT_UP((M), URT_WORD))
""", """/* Bytes of the packed A operand of a P x M weight matrix (any chunking). */
#define URT_A_BYTES(P, M)   (URT_UP((P), SA_SIZE) * URT_UP((M), URT_WORD))

/* ─── URSA v3 layout (patched by netmendes_v3/patch_runtime.py) ────────────
   A and B tile-major, one word per reduction step; C tile-major, SA x SA int32
   per tile, row-major inside the tile (ursa_v3_layout.h). Per reduction chunk
   the packed A of a P_pad x len block takes (P_pad/SA) * kw(len) * WB bytes,
   never more than the v2 P_pad * up(len, word), so the v2 offsets (chunk c at
   P_pad * k0) still hold; a row block p0.. of a chunk starts at
   (p0/SA) * kw(len) * WB inside it. */
#include "ursa_v3_layout.h"
#define URT_V3_WB          ursa3_wb(SA_SIZE)
#define URT_V3_L           ursa3_lanes(SA_SIZE)
#define URT_V3_KW(len)     ((uint32_t)ursa3_kw(SA_SIZE, (int)(len)))
#define URT_V3_A_BLK(pc, len)  ((uint32_t)((pc) / SA_SIZE) * URT_V3_KW(len) * URT_V3_WB)
""")

    # 1. urt_plan: v3 packing of each chunk
    s = rep(s, """        int8_t *dst = g->a_packed + (long)g->P_pad * k0;
        for (int p = 0; p < g->P_pad; p++) {
            for (int kk = 0; kk < mw; kk++) {
                int8_t v = 0;
                if (p < g->P && kk < len)
                    v = g->w[(long)p * g->w_ps + (long)(k0 + kk) * g->w_ks];
                dst[(long)p * mw + kk] = v;
            }
        }""", """        int8_t *dst = g->a_packed + (long)g->P_pad * k0;
        const uint32_t kwc = URT_V3_KW(len);
        memset(dst, 0, (size_t)g->P_pad * mw);
        for (int p = 0; p < g->P; p++) {
            for (int kk = 0; kk < len; kk++) {
                const long at = ((long)(p / SA_SIZE) * kwc + kk / URT_V3_L) * URT_V3_WB
                              + (kk % URT_V3_L) * SA_SIZE + p % SA_SIZE;
                dst[at] = g->w[(long)p * g->w_ps + (long)(k0 + kk) * g->w_ks];
            }
        }""")

    # 2. urt_tile: v3 sizes
    s = rep(s, """    const int m_max = URT_MINI(g->m_chunk, g->M);
    const int mw_max = URT_UP(m_max, URT_WORD);
    long best_calls = -1;

    for (int qc = SA_SIZE; qc <= g->Q_pad; qc += SA_SIZE) {
        if ((long)m_max * qc > BRAM_BI_SIZE) break;
        int pc = URT_MINI(g->P_pad, (BRAM_CA_SIZE / 4) / qc);
        if (g->a_res < 0) pc = URT_MINI(pc, BRAM_AW_SIZE / mw_max);""", """    const int m_max = URT_MINI(g->m_chunk, g->M);
    const int a_rows = (int)((BRAM_AW_SIZE / (URT_V3_KW(m_max) * URT_V3_WB)) * SA_SIZE);
    long best_calls = -1;

    for (int qc = SA_SIZE; qc <= g->Q_pad; qc += SA_SIZE) {
        if ((long)ursa3_b_bytes(SA_SIZE, m_max, qc) > BRAM_BI_SIZE) break;
        int pc = URT_MINI(g->P_pad, (BRAM_CA_SIZE / 4) / qc);
        if (g->a_res < 0) pc = URT_MINI(pc, a_rows);""")

    # 3. host model of the v3 IP
    old_model_start = "static inline uint8_t urt_model_mxm(uint32_t p, uint32_t q, uint32_t m, uint32_t a_off)\n{"
    i = s.index(old_model_start)
    j = s.index("\n}\n", i) + 3
    s = s[:i] + """static inline uint8_t urt_model_mxm(uint32_t p, uint32_t q, uint32_t m, uint32_t a_off)
{
    if (m == 0 || m > URSA_MAX_M) return 1;
#if URT_CHECK
    if (p % SA_SIZE || q % SA_SIZE || a_off % URT_V3_WB) {
        printf("[urt] model: misaligned call p=%u q=%u a_off=%u\\n", p, q, a_off);
        return 1;
    }
    if (a_off + URT_V3_A_BLK(p, m) > BRAM_AW_SIZE || ursa3_b_bytes(SA_SIZE, m, q) > BRAM_BI_SIZE
            || p * q * 4 > BRAM_CA_SIZE) {
        printf("[urt] model: call p=%u q=%u m=%u leaves the windows\\n", p, q, m);
        return 1;
    }
#endif
    /* v3: A and B tile-major (word = one step k per lane), C tile-major. */
    const uint32_t kw = URT_V3_KW(m), wb = URT_V3_WB, L = URT_V3_L, tb = q / SA_SIZE;
    const int8_t *a = URT_WIN_A + a_off;
    const uint8_t *b = URT_WIN_B;
    for (uint32_t i = 0; i < p; i++) {
        for (uint32_t j = 0; j < q; j++) {
            int32_t acc = 0;                       /* exact: m*128*255 < 2^31 */
            for (uint32_t k = 0; k < m; k++) {
                const int32_t av = a[((i / SA_SIZE) * kw + k / L) * wb + (k % L) * SA_SIZE + i % SA_SIZE];
                const int32_t bv = b[((j / SA_SIZE) * kw + k / L) * wb + (k % L) * SA_SIZE + j % SA_SIZE];
                acc += av * bv;
            }
            int32_t wrapped = (int32_t)((uint32_t)acc & ((1u << ACC_BITS) - 1u));
            if (wrapped >= (1 << (ACC_BITS - 1))) wrapped -= (1 << ACC_BITS);
            if (wrapped != acc) urt_st.wraps++;
            URT_WIN_C[((i / SA_SIZE) * tb + j / SA_SIZE) * SA_SIZE * SA_SIZE
                      + (i % SA_SIZE) * SA_SIZE + j % SA_SIZE] = wrapped;
        }
    }
    return 0;
}
""" + s[j:]

    # 4. staging buffer for B
    s = rep(s, """#ifndef USE_ARM
static int32_t urt_cstage[BRAM_CA_SIZE / 4];
#endif""", """#ifndef USE_ARM
static int32_t urt_cstage[BRAM_CA_SIZE / 4];
static uint8_t urt_bstage[BRAM_BI_SIZE] __attribute__((aligned(32)));   /* v3: packed B */
#endif""")

    # 5. urt_gemm_run: B, A, C
    s = rep(s, """            /* B: rows k0 .. k0+len, columns q0 .. q0+qc */
            if (qc == g->Q_pad) {
                memcpy(URT_WIN_B, b + (long)k0 * g->Q_pad, (size_t)len * qc);
            } else {
                for (int r = 0; r < len; r++)
                    memcpy(URT_WIN_B + (long)r * qc, b + (long)(k0 + r) * g->Q_pad + q0, (size_t)qc);
            }
            URT_FLUSH_B(URT_WIN_B, (uint32_t)len * qc);
            URT_LAP(URT_ST_XFER);""", """            /* B: rows k0 .. k0+len, columns q0 .. q0+qc, packed tile-major in
               DDR (cached) and sent to the window in one block copy. */
            const uint32_t nb = ursa3_b_bytes(SA_SIZE, len, qc);
            ursa3_pack_b(urt_bstage, b + (long)k0 * g->Q_pad + q0, g->Q_pad, SA_SIZE, len, qc);
            memcpy(URT_WIN_B, urt_bstage, nb);
            URT_FLUSH_B(URT_WIN_B, nb);
            URT_LAP(URT_ST_XFER);""")
    s = rep(s, """                const long blk = (long)g->P_pad * k0 + (long)p0 * mw;
                uint32_t a_off;
                if (g->a_res >= 0) {
                    a_off = (uint32_t)(g->a_res + blk);
                } else {
                    memcpy(URT_WIN_A, g->a_packed + blk, (size_t)pc * mw);
                    URT_FLUSH_A(URT_WIN_A, (uint32_t)pc * mw);
                    a_off = 0;
                }""", """                const long blk = (long)g->P_pad * k0 + (long)(p0 / SA_SIZE) * URT_V3_KW(len) * URT_V3_WB;
                const uint32_t a_bytes = URT_V3_A_BLK(pc, len);
                (void)mw;
                uint32_t a_off;
                if (g->a_res >= 0) {
                    a_off = (uint32_t)(g->a_res + blk);
                } else {
                    memcpy(URT_WIN_A, g->a_packed + blk, (size_t)a_bytes);
                    URT_FLUSH_A(URT_WIN_A, a_bytes);
                    a_off = 0;
                }""")
    s = rep(s, """                URT_INVALIDATE_C(URT_WIN_C, (uint32_t)pc * qc * 4);
                if (c == 0) {
                    for (int r = 0; r < pc; r++)
                        memcpy(acc + (long)(p0 + r) * g->Q_pad + q0, URT_WIN_C + (long)r * qc,
                               sizeof(int32_t) * qc);
                } else {
                    memcpy(urt_cstage, URT_WIN_C, sizeof(int32_t) * pc * qc);
                    for (int r = 0; r < pc; r++) {
                        int32_t *dst = acc + (long)(p0 + r) * g->Q_pad + q0;
                        const int32_t *src = urt_cstage + (long)r * qc;
                        for (int j = 0; j < qc; j++) dst[j] += src[j];
                    }
                }""", """                URT_INVALIDATE_C(URT_WIN_C, (uint32_t)pc * qc * 4);
                /* v3: C is tile-major. One block copy out of the window, then
                   de-tile (first chunk) or de-tile and add (later chunks). */
                memcpy(urt_cstage, URT_WIN_C, sizeof(int32_t) * pc * qc);
                {
                    const int tbq = qc / SA_SIZE;
                    for (int r = 0; r < pc; r++) {
                        int32_t *dst = acc + (long)(p0 + r) * g->Q_pad + q0;
                        const int32_t *row = urt_cstage + (long)(r / SA_SIZE) * tbq * SA_SIZE * SA_SIZE
                                                        + (r % SA_SIZE) * SA_SIZE;
                        for (int jt = 0; jt < tbq; jt++) {
                            const int32_t *src = row + (long)jt * SA_SIZE * SA_SIZE;
                            int32_t *d = dst + jt * SA_SIZE;
                            if (c == 0) memcpy(d, src, sizeof(int32_t) * SA_SIZE);
                            else for (int x = 0; x < SA_SIZE; x++) d[x] += src[x];
                        }
                    }
                }""")

    # 5b. host: optional cross-check against the HLS C model of the IP
    s = rep(s, """#if URT_BOARD
    return mxm_execute_ursa(&xUrsa0, p, q, m,
                            (uint32_t)BRAM_AW_BASEADDR + a_off,
                            (uint32_t)BRAM_BI_BASEADDR,
                            (uint32_t)BRAM_CA_BASEADDR);
#else
    return urt_model_mxm(p, q, m, a_off);
#endif""", """#if URT_BOARD
    return mxm_execute_ursa(&xUrsa0, p, q, m,
                            (uint32_t)BRAM_AW_BASEADDR + a_off,
                            (uint32_t)BRAM_BI_BASEADDR,
                            (uint32_t)BRAM_CA_BASEADDR);
#elif defined(URT_V3_HLS)
    /* host, -DURT_V3_HLS: the HLS C model of the v3 IP itself
       (netmendes_v3/hls_bridge.cpp + sources/vanilla/src/core/*.cpp). */
    extern uint8_t urt_hls_mxm(const int8_t *a, const uint8_t *b, int32_t *c,
                               uint32_t p, uint32_t q, uint32_t m);
    return urt_hls_mxm(URT_WIN_A + a_off, URT_WIN_B, URT_WIN_C, p, q, m);
#else
    return urt_model_mxm(p, q, m, a_off);
#endif""")

    # 6. 64-bit MAC count in the report
    s = rep(s, """    printf("[urt] URSA calls per inference: %lu, MACs per inference: %lu\\n",
           (unsigned long)(urt_st.calls / n), (unsigned long)(urt_st.macs / n));""",
            """    printf("[urt] URSA calls per inference: %lu, MACs per inference: %llu\\n",
           (unsigned long)(urt_st.calls / n), (unsigned long long)(urt_st.macs / n));""")

    # 7. header line
    s = rep(s, " * URSA (UFRGS Reconfigurable Systolic Array, output-stationary v2, vanilla PE)",
            " * URSA (UFRGS Reconfigurable Systolic Array, output-stationary v3, vanilla PE)\n"
            " * [v3: layout patched by netmendes_v3/patch_runtime.py; see URSA v3 layout below]")
    return s


def main():
    src, out = sys.argv[1], sys.argv[2]
    n = 0
    for f in sorted(glob.glob(os.path.join(src, "*", "*_hwtest.cpp"))):
        rel = os.path.relpath(f, src)
        dst = os.path.join(out, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(f) as fh:
            s = fh.read()
        with open(dst, "w") as fh:
            fh.write(patch(s))
        n += 1
    for extra in ("README.txt",):
        p = os.path.join(src, extra)
        if os.path.exists(p):
            with open(p) as fh, open(os.path.join(out, extra), "w") as fo:
                fo.write(fh.read())
    print("patched %d tests -> %s" % (n, out))


if __name__ == "__main__":
    main()
